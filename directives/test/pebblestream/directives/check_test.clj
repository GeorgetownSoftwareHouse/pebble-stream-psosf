(ns pebblestream.directives.check-test
  "The whole check, on archives built with psosf.model."
  (:require [clojure.string :as string]
            [clojure.test :refer [deftest is testing]]
            [pebblestream.directives.check :as check]
            [pebblestream.directives.cli :as cli]
            [psosf.core :as psosf]
            [psosf.model :as m]))

(defn- input [name headers rows]
  (reduce m/add-row
          (reduce #(m/add-column %1 {:header %2}) (m/sheet name) headers)
          rows))

(defn- with-directives [sheet header & lines]
  (reduce #(m/add-annotation-line %1 header %2) sheet lines))

(def base
  (-> (m/archive "Distributions")
      (m/add-sheet (input "ClassNII" ["Fund ID" "Share Class" "NII ($)"] [["F1" "A" "100"]]))
      (m/add-sheet (input "FundClasses" ["Fund ID" "Share Class" "Shares"] [["F1" "A" "10"]]))
      (m/add-sheet (-> (input "ClassNIIWithShares" ["Fund ID" "Share Class" "NII ($)" "Shares"] [["F1" "A" "100" "10"]])
                       (with-directives "Fund ID"
                         "pebblestream:from(ClassNII)"
                         "pebblestream:join(FundClasses, \"Fund ID\", \"Fund ID\", \"Share Class\", \"Share Class\")")))
      (m/add-sheet (-> (input "PerShare" ["Fund ID" "Share Class" "NII ($)" "Shares" "Per Share"]
                              [["F1" "A" "100" "10" (m/formula "=C2/D2")]])
                       (with-directives "Fund ID" "pebblestream:from(ClassNIIWithShares)")
                       (with-directives "Per Share" "pebblestream:fail")))))

(defn- report [archive] (check/check-entries (psosf/write-entries archive)))
(defn- codes [r k] (set (map #(get % "code") (get r k))))
(defn- edit [sheet-name f & args] (apply m/update-sheet base sheet-name f args))

(deftest a-conforming-archive-passes
  (let [r (report base)]
    (is (true? (get r "passed")) (pr-str r))
    (is (= "valid" (get r "level")) "no allow-list is configured, which does not fail the check")
    (is (empty? (get r "errors")))))

(deftest directive-lines
  (is (= #{"unknown-directive"} (codes (report (edit "PerShare" with-directives "Per Share" "pebblestream:no-such-thing")) "errors")))
  (is (= #{"unreadable-directive"} (codes (report (edit "PerShare" with-directives "Per Share" "pebblestream:hint(\"open")) "errors")))
  (is (= #{"bad-arguments"} (codes (report (edit "PerShare" with-directives "Per Share" "pebblestream:hint(\"a\", \"b\", \"c\")")) "errors")))
  (is (contains? (codes (report (edit "PerShare" with-directives "Per Share" "pebblestream:hint:balance:closing")) "warnings")
                 "deprecated-syntax"))
  (is (contains? (codes (report (edit "PerShare" with-directives "Per Share" "pebblestream:hint(\"C:\\data\")")) "warnings")
                 "ambiguous-backslash")))

(deftest worksheet-rules
  (testing "join and outer-join together"
    (is (contains? (codes (report (edit "ClassNIIWithShares" with-directives "Fund ID" "pebblestream:outer-join(ClassNII)")) "errors")
                   "excluded-together")))
  (testing "a header argument without its units"
    (let [r (report (edit "ClassNIIWithShares" m/set-annotation "Fund ID"
                          ["pebblestream:from(ClassNII)"
                           "pebblestream:join(FundClasses, \"Fund ID\", \"Fund ID\", \"Share Class\", \"Share Class\")"
                           "pebblestream:filter(\"NII\", \">0\")"]))
          e (first (filter #(= "unknown-header" (get % "code")) (get r "errors")))]
      (is (= "Did you mean \"NII ($)\"?" (get e "fix")))))
  (testing "a formula in a transformed column"
    (let [r (report (edit "PerShare" m/set-cell 0 "Shares" (m/formula "=1")))]
      (is (some #(= "cell 'PerShare'!D2 has a formula, but its column is generated by directives." (get % "message"))
                (get r "errors")))))
  (testing "a formula reference that closes a cycle"
    (is (contains? (codes (report (-> base
                                      (m/update-sheet "ClassNIIWithShares" m/add-column {:header "Check"})
                                      (m/update-sheet "ClassNIIWithShares" m/set-cell 0 "Check" (m/formula "=PerShare!E2"))))
                          "errors")
                   "reference-to-later-worksheet")))
  (testing "ignore on a connected worksheet"
    (is (contains? (codes (report (m/add-sheet base (-> (input "Expected" ["Match"] [[(m/formula "=PerShare!E2=10")]])
                                                       (with-directives "Match" "pebblestream:ignore"))))
                          "errors")
                   "ignore-on-connected-worksheet")))
  (testing "blank in allowed-values"
    (is (contains? (codes (report (edit "ClassNII" with-directives "Share Class" "pebblestream:allowed-values(\"A\", \"blank\")")) "errors")
                   "blank-in-allowed-values")))
  (testing "a deprecated group directive, with its replacement"
    (let [r (report (-> base
                        (m/add-sheet (input "Totals" ["Fund ID" "NII ($)"] [["F1" "100"]]))
                        (m/update-sheet "Totals" with-directives "Fund ID"
                                        "pebblestream:from(ClassNII)" "pebblestream:group-sum(\"Fund ID\", \"NII ($)\")")))
          w (first (filter #(= "deprecated-directive" (get % "code")) (get r "warnings")))]
      (is (= "Replace it with pebblestream:group(\"Fund ID\") and pebblestream:sum(\"NII ($)\")." (get w "fix"))))))

(deftest structure-comes-first
  (let [entries (assoc (psosf/write-entries base) "PerShare.csv" "broken")
        r (check/check-entries entries)]
    (is (false? (get r "passed")))
    (is (= "invalid" (get r "level")))))

(deftest acceptance-errors-fail-the-check
  (let [r (check/check-entries (psosf/write-entries (edit "PerShare" m/set-cell 0 "Per Share" (m/formula "=WEBSERVICE(\"x\")")))
                               {"allowed-functions" ["SUM"]})]
    (is (false? (get r "passed")))
    (is (= #{"function-not-allowed"} (codes r "acceptance-errors")))))

(deftest command-line
  (let [tmp (java.io.File/createTempFile "check" ".psosf")]
    (psosf/write-file tmp base)
    (let [out (with-out-str (is (= 0 (cli/run [(str tmp)]))))]
      (is (string/includes? out "\"passed\": true")))
    (psosf/write-file tmp (edit "ClassNII" with-directives "Share Class" "pebblestream:allowed-values(\"blank\")"))
    (let [out (with-out-str (is (= 1 (cli/run [(str tmp) "--allow" "SUM"]))))]
      (is (string/includes? out "blank-in-allowed-values")))))
