(ns pebblestream.directives.worksheet-rules-test
  "The worksheet rules, checked on spreadsheets modelled on the two-join and
   grouping patterns from the authoring rules."
  (:require [clojure.test :refer [deftest is testing]]
            [pebblestream.directives.schema :as s]))

(def inputs
  [{:name "ClassNII"           :headers ["Fund ID" "Share Class" "NII ($)"]   :directives [] :formulas {}}
   {:name "FundClasses"        :headers ["Fund ID" "Share Class" "Shares"]    :directives [] :formulas {}}
   {:name "ClassROCAllocation" :headers ["Fund ID" "Share Class" "ROC ($)"]   :directives [] :formulas {}}
   {:name "FundExpensesShared" :headers ["Fund ID" "Annual Amount ($)"]       :directives [] :formulas {}}])

(def with-shares
  {:name "ClassNIIWithShares"
   :headers ["Fund ID" "Share Class" "NII ($)" "Shares"]
   :directives [{:directive :from :args ["ClassNII"]}
                {:directive :join :args ["FundClasses" "Fund ID" "Fund ID" "Share Class" "Share Class"]}]
   :formulas {}})

(def per-share
  {:name "PerShareDistribution"
   :headers ["Fund ID" "Share Class" "NII ($)" "Shares" "ROC ($)" "Per Share"]
   :directives [{:directive :from :args ["ClassNIIWithShares"]}
                {:directive :join :args ["ClassROCAllocation" "Fund ID" "Fund ID" "Share Class" "Share Class"]}]
   :formulas {"Per Share" #{}}})

(def shared-totals
  {:name "SharedExpenseTotals"
   :headers ["Fund ID" "Total Shared Expense ($)"]
   :directives [{:directive :from :args ["FundExpensesShared"]}
                {:directive :group :args ["Fund ID"]}
                {:directive :sum :args ["Annual Amount ($)"]}
                {:directive :header-map :args ["Annual Amount ($)" "Total Shared Expense ($)"]}]
   :formulas {}})

(def good (into inputs [with-shares per-share shared-totals]))

(defn- check [sheets] (s/spreadsheet-errors {:sheets sheets}))
(defn- codes [sheets] (mapv :code (:errors (check sheets))))
(defn- replace-sheet [sheets sheet] (mapv #(if (= (:name %) (:name sheet)) sheet %) sheets))

(deftest a-conforming-spreadsheet
  (is (= {:errors [] :warnings []} (check good))))

(deftest one-join-per-worksheet
  (testing "join and outer-join together"
    (let [r (check (replace-sheet good (update with-shares :directives conj
                                               {:directive :outer-join :args ["ClassROCAllocation"]})))]
      (is (= [:excluded-together] (map :code (:errors r))))
      (is (re-find #"intermediate worksheet" (:fix (first (:errors r)))))))
  (testing "two joins"
    (is (= [:repeated-directive]
           (codes (replace-sheet good (update with-shares :directives conj
                                              {:directive :join :args ["ClassROCAllocation"]}))))))
  (testing "a sub-directive without its required directive"
    (is (= [:missing-required]
           (codes (replace-sheet good (update shared-totals :directives #(remove (comp #{:group} :directive) %))))))))

(deftest header-arguments-match-exactly
  (let [r (check (replace-sheet good (assoc-in shared-totals [:directives 2 :args] ["Annual Amount"])))]
    (is (= [:unknown-header] (map :code (:errors r))))
    (is (= "Did you mean \"Annual Amount ($)\"?" (:fix (first (:errors r))))))
  (testing "a header-map target must be a header of the worksheet"
    (is (= [:unknown-header]
           (codes (replace-sheet good (assoc-in shared-totals [:directives 3 :args] ["Annual Amount ($)" "Total"]))))))
  (testing "a joined column must exist on the joined worksheet"
    (is (= [:unknown-header]
           (codes (replace-sheet good (assoc-in with-shares [:directives 1 :args 2] "FundID"))))))
  (testing "an unknown source worksheet"
    (is (= [:unknown-worksheet]
           (codes (replace-sheet good (assoc-in with-shares [:directives 0 :args] ["ClassNIII"])))))))

(deftest transformed-and-generated-columns
  (testing "a formula in a transformed column"
    (let [r (check (replace-sheet good (assoc per-share :formulas {"Per Share" #{} "Shares" #{}})))]
      (is (= [:formula-in-transformed-column] (map :code (:errors r))))
      (is (= "cell 'PerShareDistribution'!D2 has a formula, but its column is generated by directives."
             (:message (first (:errors r)))))))
  (testing "a column that no directive fills and that has no formula is allowed"
    (is (empty? (codes (replace-sheet good (assoc per-share :formulas {}))))))
  (testing "a formula may refer to any worksheet created before its own"
    (is (empty? (codes (replace-sheet good (assoc per-share :formulas {"Per Share" #{"ClassNIIWithShares"}}))))
        "an earlier transformed worksheet")
    (is (empty? (codes (replace-sheet good (assoc per-share :formulas {"Per Share" #{"FundClasses"}}))))
        "an input worksheet"))
  (testing "but not to one that depends on its own worksheet, which would form a cycle"
    (let [early (assoc with-shares :headers (conj (:headers with-shares) "Check")
                                   :formulas {"Check" #{"PerShareDistribution"}})
          r     (check (replace-sheet good early))]
      (is (= [:reference-to-later-worksheet] (map :code (:errors r))))
      (is (= "The formulas in \"Check\" refer to \"PerShareDistribution\", which depends on \"ClassNIIWithShares\", so the two worksheets form a cycle."
             (:message (first (:errors r))))))))

(deftest directive-cycles
  (let [a {:name "A" :headers ["x"] :directives [{:directive :from :args ["B"]}] :formulas {}}
        b {:name "B" :headers ["x"] :directives [{:directive :from :args ["A"]}] :formulas {}}]
    (is (= [:dependency-cycle :dependency-cycle] (codes [a b])))))

(deftest ignore-only-on-isolated-worksheets
  (let [expected {:name "ExpectedResults" :headers ["Fund ID" "Matches"]
                  :directives [{:directive :ignore}] :formulas {}}]
    (is (empty? (codes (conj good expected))) "an isolated worksheet")
    (is (= [:ignore-on-connected-worksheet]
           (codes (conj good (assoc expected :formulas {"Matches" #{"PerShareDistribution"}}))))
        "a worksheet comparing itself with an output by formula")))

(deftest allowed-values-has-no-blank-keyword
  (let [sheet (fn [vals] (update (first inputs) :directives conj {:directive :allowed-values :args vals :column "NII ($)"}))]
    (is (empty? (codes (replace-sheet good (sheet [">=0"])))))
    (let [r (check (replace-sheet good (sheet ["A" "blank"])))]
      (is (= [:blank-in-allowed-values] (map :code (:errors r))))
      (is (re-find #"not-blank" (:fix (first (:errors r))))))))

(deftest deprecated-group-directives
  (let [old (assoc shared-totals
                   :headers ["Fund ID" "Annual Amount ($)"]
                   :directives [{:directive :from :args ["FundExpensesShared"]}
                                {:directive :group-sum :args ["Fund ID" "Annual Amount ($)"]}])
        w   (:warnings (check (replace-sheet good old)))]
    (is (= [:deprecated-directive] (map :code w)))
    (is (= "Replace it with pebblestream:group(\"Fund ID\") and pebblestream:sum(\"Annual Amount ($)\")."
           (:fix (first w)))))
  (is (= "pebblestream:group(\"Fund ID\") and pebblestream:ratio(\"Average Net Assets ($)\")"
         (s/deprecated-replacement {:directive :group-ratio :args ["Fund ID" "Average Net Assets ($)"]})))
  (is (= "pebblestream:group(\"Fund ID\", \"Fund Name\")"
         (s/deprecated-replacement {:directive :group-unique :args ["Fund ID" "Fund Name"]}))))

(deftest once-per-spreadsheet-across-worksheets
  (is (= [:repeated-directive]
         (codes (-> good
                    (replace-sheet (update with-shares :directives conj {:directive :workflow-each}))
                    (replace-sheet (update per-share :directives conj {:directive :workflow-each})))))))
